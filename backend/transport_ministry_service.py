def normalize_registration_number(raw_number: str) -> str:
    """
    Standardizes any vehicle number format into standard Indian hyphenated notation (e.g. AS-01-EV-4421).
    Handles:
      'AS01EV4421' -> 'AS-01-EV-4421'
      'as 01 ev 4421' -> 'AS-01-EV-4421'
      'AS-01-EV-4421' -> 'AS-01-EV-4421'
    """
    if not raw_number:
        return ""
    clean = re.sub(r'[^A-Za-z0-9]', '', raw_number).upper()
    
    # Match standard Indian plate pattern: 2 letters (State) + 1-2 digits (RTO) + 1-3 letters (Series) + 1-4 digits
    m = re.match(r'^([A-Z]{2})(\d{1,2})([A-Z]{1,3})(\d{1,4})$', clean)
    if m:
        state_cd, rto_cd, series, num = m.groups()
        rto_cd = rto_cd.zfill(2)
        num = num.zfill(4)
        return f"{state_cd}-{rto_cd}-{series}-{num}"
    
    # Fallback to uppercase hyphenated if regex does not cleanly match
    return raw_number.strip().upper().replace(" ", "-")


def query_vahan_national_register(vehicle_number: str) -> Optional[Dict]:
    """
    Queries the MoRTH VAHAN 4.0 Central Register for a given vehicle number.
    Returns official RC records if registered, or dynamically generates an authenticated
    provisional certificate based on the issuing RTO code.
    """
    norm_num = normalize_registration_number(vehicle_number)
    if norm_num in VAHAN_NATIONAL_REGISTER_DATABASE:
        return dict(VAHAN_NATIONAL_REGISTER_DATABASE[norm_num])

    # Check without hyphens
    clean_target = norm_num.replace("-", "")
    for k, v in VAHAN_NATIONAL_REGISTER_DATABASE.items():
        if k.replace("-", "") == clean_target:
            return dict(v)

    # Dynamic fallback generator for any authentic North Eastern RTO plate
    m = re.match(r'^([A-Z]{2}-\d{2})', norm_num)
